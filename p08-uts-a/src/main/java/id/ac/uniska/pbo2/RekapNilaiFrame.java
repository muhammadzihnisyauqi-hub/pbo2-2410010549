    private void siapkanTampilan() {
        setLocationRelativeTo(null);
        getRootPane().setDefaultButton(btnSimpan);

        // Hubungkan JTable dengan model tabel buatan sendiri.
        tblMahasiswa.setModel(modelTabel);
        tblMahasiswa.getColumnModel().getColumn(0).setPreferredWidth(110);
        tblMahasiswa.getColumnModel().getColumn(1).setPreferredWidth(200);
        for (int kolom = 2; kolom <= 5; kolom++) {
            tblMahasiswa.getColumnModel().getColumn(kolom).setPreferredWidth(70);
        }
        tblMahasiswa.getColumnModel().getColumn(6).setPreferredWidth(60);

        // Kolom Akhir berisi teks (82,50) sehingga dibuat rata kanan secara manual.
        DefaultTableCellRenderer rataKanan = new DefaultTableCellRenderer();
        rataKanan.setHorizontalAlignment(SwingConstants.RIGHT);
        tblMahasiswa.getColumnModel().getColumn(5).setCellRenderer(rataKanan);

        // Pesan kesalahan berwarna merah.
        lblPesan.setForeground(new Color(204, 0, 0));

        // Placeholder (fitur FlatLaf).
        txtNpm.putClientProperty("JTextField.placeholderText", "10 digit angka");
        txtTugas.putClientProperty("JTextField.placeholderText", "0 sampai 100");
        txtUts.putClientProperty("JTextField.placeholderText", "0 sampai 100");
        txtUas.putClientProperty("JTextField.placeholderText", "0 sampai 100");
    }

    private void simpan() {
        hapusTandaError();

        String npm = txtNpm.getText().strip();
        String nama = txtNama.getText().strip();

        if (!npm.matches("[0-9]{10}")) {
            tampilkanError("NPM harus 10 digit angka", txtNpm);
            return;
        }
        if (modelTabel.adaNpm(npm)) {
            tampilkanError("NPM " + npm + " sudah terdaftar", txtNpm);
            return;
        }
        if (nama.isEmpty()) {
            tampilkanError("Nama wajib diisi", txtNama);
            return;
        }

        int tugas = bacaNilai(txtTugas, "Nilai Tugas");
        if (tugas < 0) {
            return;
        }
        int uts = bacaNilai(txtUts, "Nilai UTS");
        if (uts < 0) {
            return;
        }
        int uas = bacaNilai(txtUas, "Nilai UAS");
        if (uas < 0) {
            return;
        }

        modelTabel.tambah(new NilaiMahasiswa(npm, nama, tugas, uts, uas));
        bersihkanForm();
        perbaruiRingkasan();

        // Gulung tabel ke baris terakhir.
        int barisTerakhir = modelTabel.getRowCount() - 1;
        tblMahasiswa.scrollRectToVisible(tblMahasiswa.getCellRect(barisTerakhir, 0, true));
    }

    /**
     * Membaca isian nilai. Mengembalikan angka 0 sampai 100,
     * atau -1 jika tidak valid (pesan kesalahan sudah ditampilkan).
     */
    private int bacaNilai(JTextField field, String namaNilai) {
        String teks = field.getText().strip();
        if (teks.matches("[0-9]{1,9}")) {
            int nilai = Integer.parseInt(teks);
            if (nilai <= 100) {
                return nilai;
            }
        }
        tampilkanError(namaNilai + " harus angka bulat 0 sampai 100", field);
        return -1;
    }

    private void tampilkanError(String pesan, JTextField fieldSalah) {
        lblPesan.setText(pesan);
        fieldSalah.putClientProperty("JComponent.outline", "error");
        fieldSalah.requestFocusInWindow();
    }

    private void hapusTandaError() {
        lblPesan.setText("");
        txtNpm.putClientProperty("JComponent.outline", null);
        txtNama.putClientProperty("JComponent.outline", null);
        txtTugas.putClientProperty("JComponent.outline", null);
        txtUts.putClientProperty("JComponent.outline", null);
        txtUas.putClientProperty("JComponent.outline", null);
    }

    /** Mengosongkan semua isian dan pesan kesalahan. */
    private void bersihkanForm() {
        txtNpm.setText("");
        txtNama.setText("");
        txtTugas.setText("");
        txtUts.setText("");
        txtUas.setText("");
        hapusTandaError();
        txtNpm.requestFocusInWindow();
    }

    private void perbaruiRingkasan() {
        lblRingkasan.setText("Jumlah mahasiswa: " + modelTabel.getJumlah()
                + ", rata-rata nilai akhir: " + modelTabel.getRataRataAkhirTeks());
    }

