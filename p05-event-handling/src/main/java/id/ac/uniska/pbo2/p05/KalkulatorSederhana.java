    /** Menampilkan bilangan bulat tanpa ".0", misalnya 12.0 menjadi 12. */
    private static String rapikan(double nilai) {
        if (nilai == Math.rint(nilai)) {
            return String.valueOf((long) nilai);
        }
        return String.valueOf(nilai);
    }

