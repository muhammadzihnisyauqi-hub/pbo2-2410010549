private void perbaruiJumlahDigit() {
    int jumlah = npmField.getText().trim().length();
    jumlahDigitLabel.setText(jumlah + " dari " + MAKS_DIGIT_NPM + " digit");
}

private void kosongkanIsian() {
    npmField.setText("");
    namaField.setText("");
    prodiCombo.setSelectedIndex(0);
    mahasiswaRadio.setSelected(false);
    dosenRadio.setSelected(false);
    umumRadio.setSelected(false);
    emailField.setText("");
    hpField.setText("");
    alamatTextArea.setText("");
    setujuCheck.setSelected(false);
    perbaruiJumlahDigit();
    npmField.requestFocusInWindow();
}

